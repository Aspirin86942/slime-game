function eventKind(row:[string,string,string,string],i:number):string {
 if(row[1].includes('幼体'))return '救助';
 if(/擂台|守卫|守门人|挑战|切磋|试题/.test(row[0]))return '挑战';
 if(/箭头|倒影|时钟|指针|回声/.test(row[0]))return '谜题';
 if(/商|交换/.test(row[1]))return '交易';
 if(i===11)return '故事';
 if(i===10)return '伙伴';
 return i%2===0?'调查':'采集';
}
